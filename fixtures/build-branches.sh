#!/usr/bin/env bash
# ==============================================================================
# DCMS system-test fixture corpus generator
#
# Builds every `fx/*` branch described in SYSTEM-TEST.MD 1.5 / 8.7 / 8.8 from
# scratch, so the deterministic half of the repo corpus is version-controlled,
# reproducible, and diffable between runs. Public repos change under us; these
# do not.
#
#   usage:  ./build-branches.sh <remote-url> [--push]
#
# Idempotent: re-running rebuilds every branch from the same base and
# force-pushes, so a branch can never drift from what this script says it is.
#
# Deliberately NOT built here (see the notes at the bottom of this file):
#   fx/lfs         -- needs git-lfs, which is intentionally absent on the
#                     DCMS host so R-WX-02 measures the real clone behaviour
#   fx/big-binary  -- GitHub rejects blobs over 100 MB without LFS
# ==============================================================================
set -euo pipefail

REMOTE="${1:?usage: build-branches.sh <remote-url> [--push]}"
PUSH="${2:-}"
# The remote with any embedded credentials stripped. Anything that gets COMMITTED
# must use this form -- a token in tracked content is published forever.
CLEAN_REMOTE="$(printf '%s' "$REMOTE" | sed -E 's#//[^/@]*@#//#')"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$WORK"
git init -q -b main .
git config user.email "systest@dcms.local"
git config user.name  "DCMS System Test"
git config core.autocrlf false

# ------------------------------------------------------------------ helpers --
commit() { git add -A; git commit -qm "$1"; }

# Start every fx/ branch from the same known-good base so a diff against main
# shows exactly, and only, the scenario under test.
from_main() { git checkout -q main; git checkout -q -B "$1"; }

node_app() {
  cat > package.json <<'JSON'
{
  "name": "dcms-fixture",
  "version": "1.0.0",
  "private": true,
  "scripts": { "start": "node server.js" }
}
JSON
  cat > server.js <<'JS'
const http = require('http');
const port = process.env.PORT || 3000;
const marker = process.env.DCMS_FIXTURE_MARKER || 'dcms-fixture-ok';
http.createServer((req, res) => {
  if (req.url === '/health') { res.writeHead(200); return res.end('ok'); }
  res.writeHead(200, { 'Content-Type': 'text/html' });
  res.end(`<!doctype html><title>DCMS fixture</title><h1>${marker}</h1><p>branch marker</p>`);
}).listen(port, '0.0.0.0', () => console.log('listening on ' + port));
JS
}

