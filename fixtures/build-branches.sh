# ------------------------------------------------------------------ fx/submodules --
# R-WX-01: a real git submodule, pointing at this same repo so the fixture stays
# self-contained and depends on no third party.
#
# This runs AFTER the push on purpose. A submodule needs its target to have at
# least one commit, and on a first run the remote is empty until the push above
# lands -- so building this branch earlier fails with
# "does not have a commit checked out".
if [ "$PUSH" = "--push" ]; then
  from_main fx/submodules
  if git -c protocol.file.allow=always submodule add -q -b main "$REMOTE" vendor/self 2>/dev/null; then
    # `submodule add` records whatever URL it was given -- including credentials.
    # Writing the tokenised URL into .gitmodules would publish the PAT in a repo
    # that is public; GitHub push protection rejects it, and rightly so. Rewrite
    # the recorded URL to the credential-free form before committing. The push
    # itself still authenticates through `origin`.
    git config -f .gitmodules submodule.vendor/self.url "$CLEAN_REMOTE"
    git add .gitmodules
    commit "fx/submodules: one git submodule (R-WX-01)"
    git push -q --force origin fx/submodules
    echo "pushed fx/submodules"
  else
    echo "WARNING: fx/submodules could not be built (submodule add failed); branch skipped" >&2
  fi
  git checkout -q main
fi

